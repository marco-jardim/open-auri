// Post-build step of `npm run build` (#33): wraps the Worker entry that
// @sveltejs/adapter-cloudflare writes, so the canonical-host decision runs before the adapter
// serves a prerendered page from Static Assets (why: src/worker-entry/canonical-host.ts).
//
//   1. <dir>/_worker.js (the wrangler `main`, .svelte-kit/cloudflare/_worker.js) is renamed to
//      _sveltekit.js in the same directory, so its relative imports (./../cloudflare-tmp/server.js)
//      still resolve;
//   2. a new _worker.js re-exports its named exports and default-exports
//      withCanonicalHost(<its default export>); wrangler bundles both, TypeScript source included,
//      on `wrangler dev` and `wrangler deploy`;
//   3. _sveltekit.js joins .assetsignore (the directory is also the assets directory), so the server
//      code is never uploaded as a public static file.
// Idempotent: a _worker.js that already carries MARKER is left alone, so a second run without a new
// `vite build` cannot wrap the wrapper.
//
// Usage: node scripts/wrap-worker.mjs [<worker directory>]
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const MARKER = '// GENERATED by web/scripts/wrap-worker.mjs';
export const WORKER = '_worker.js';
export const INNER = '_sveltekit.js';
const ASSETS_IGNORE = '.assetsignore';
const DEFAULT_DIR = fileURLToPath(new URL('../.svelte-kit/cloudflare/', import.meta.url));
/** The wrapper module the generated entry imports. */
export const ENTRY = fileURLToPath(
	new URL('../src/worker-entry/canonical-host.ts', import.meta.url)
);
const USAGE = 'Usage: node scripts/wrap-worker.mjs [<worker directory>]';

/** Relative POSIX import specifier from `dir` to `file` (starts with ./ or ../). */
function specifierFrom(dir, file) {
	const path = relative(dir, file);
	if (isAbsolute(path)) throw new Error(`Cannot import ${file} relatively from ${dir}`);
	const posix = path.replace(/\\/g, '/');
	return posix.startsWith('.') ? posix : `./${posix}`;
}

/** Source of the generated _worker.js in `dir`. */
export function wrapperSource(dir, entry = ENTRY) {
	const inner = JSON.stringify(`./${INNER}`);
	return [
		`${MARKER} after \`vite build\`; do not edit.`,
		`import sveltekit from ${inner};`,
		`import { withCanonicalHost } from ${JSON.stringify(specifierFrom(dir, entry))};`,
		`export * from ${inner};`,
		'export default withCanonicalHost(sveltekit);',
		''
	].join('\n');
}

/** Adds the missing `names` to `dir`/.assetsignore, keeping its lines. */
function ignoreAssets(dir, names) {
	const path = join(dir, ASSETS_IGNORE);
	const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
	const lines = new Set(current.split(/\r?\n/).map((line) => line.trim()));
	const missing = names.filter((name) => !lines.has(name));
	if (!missing.length) return;
	const prefix = current === '' || current.endsWith('\n') ? current : `${current}\n`;
	writeFileSync(path, `${prefix}${missing.join('\n')}\n`);
}

/**
 * Wraps `dir`/_worker.js. Returns 'wrapped', or 'unchanged' when it is already the wrapper.
 * Throws when there is no _worker.js (no `vite build` yet).
 */
export function wrapWorker(dir = DEFAULT_DIR, entry = ENTRY) {
	const worker = join(dir, WORKER);
	if (!existsSync(worker)) throw new Error(`Missing ${worker}: run vite build first`);
	if (readFileSync(worker, 'utf8').startsWith(MARKER)) return 'unchanged';
	const source = wrapperSource(dir, entry);
	rmSync(join(dir, INNER), { force: true });
	renameSync(worker, join(dir, INNER));
	writeFileSync(worker, source);
	ignoreAssets(dir, [WORKER, INNER]);
	return 'wrapped';
}

function main() {
	const args = process.argv.slice(2);
	if (args.length > 1 || args.some((arg) => arg.startsWith('-'))) throw new Error(USAGE);
	const dir = args[0] === undefined ? DEFAULT_DIR : resolve(args[0]);
	const result = wrapWorker(dir);
	console.log(
		result === 'wrapped'
			? `wrap-worker: ${WORKER} now wraps ${INNER} with the canonical-host check`
			: `wrap-worker: ${WORKER} is already the wrapper`
	);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	try {
		main();
	} catch (error) {
		console.error(error instanceof Error ? error.message : 'wrap-worker failed');
		process.exitCode = 1;
	}
}
